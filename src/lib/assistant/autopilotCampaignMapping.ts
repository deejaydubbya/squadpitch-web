/**
 * Resolves the action for status_changed triggers.
 * For non-status_changed triggers, always returns 'generate'.
 */
function resolveStatusAction(
  triggerType: AutopilotTriggerType,
  propertyData: Record<string, unknown>,
): StatusChangeAction {
  if (triggerType !== 'status_changed') return 'generate';

  const listingStatus = (propertyData.listingStatus as string | undefined)?.toLowerCase();

  // Terminal statuses — skip generation
  if (listingStatus === 'sold' || listingStatus === 'closed' || listingStatus === 'withdrawn' || listingStatus === 'expired' || listingStatus === 'cancelled') {
    return 'pause';
  }

  // Pending — skip generation
  if (listingStatus === 'pending' || listingStatus === 'under_contract') {
    return 'skip';
  }

  // Active/other — generate
  return 'generate';
}

/**
 * Determines whether a new trigger type should supersede an existing one.
 * More specific/urgent triggers supersede less specific ones.
 */
function shouldSupersede(
  newTrigger: AutopilotTriggerType,
  existingTrigger: AutopilotTriggerType,
): boolean {
  // Spinstr05 priority order:
  //   open_house > price_drop > new_listing > just_sold > new_review >
  //   stale_listing > seasonal > inactivity_gap > status_changed (legacy)
  const priority: Record<AutopilotTriggerType, number> = {
    open_house_added: 9,
    open_house_updated: 8,
    price_drop: 7,
    new_listing: 6,
    just_sold: 5,
    new_review: 4,
    stale_listing: 3,
    seasonal: 2,
    inactivity_gap: 1,
    status_changed: 0,
  };

  return (priority[newTrigger] ?? 0) > (priority[existingTrigger] ?? 0);
}

/**
 * Builds a human-readable rationale string.
 */
function buildRationale(
  triggerType: AutopilotTriggerType,
  campaignType: CampaignTypeRecommendation,
  propertyData: Record<string, unknown>,
): string {
  const price = propertyData.price as number | undefined;
  const previousPrice = propertyData.previousPrice as number | undefined;
  const title = (propertyData.title as string) || (propertyData.address as string) || 'this property';

  switch (triggerType) {
    case 'new_listing':
      return `New listing detected for ${title}. ${campaignType.reason}`;
    case 'price_drop': {
      const drop = previousPrice && price
        ? ` ($${((previousPrice - price) / 1000).toFixed(0)}k reduction)`
        : '';
      return `Price drop detected for ${title}${drop}. Urgency-driven campaigns perform 2-3x better in the first 48 hours.`;
    }
    case 'open_house_added':
      return `Open house scheduled for ${title}. A campaign driving attendance should launch 3-5 days before the event.`;
    case 'open_house_updated':
      return `Open house details updated for ${title}. A reminder campaign can recapture interest from earlier viewers.`;
    case 'status_changed': {
      const status = (propertyData.listingStatus as string) ?? 'unknown';
      return `Listing status changed to "${status}" for ${title}. ${campaignType.reason}`;
    }
    default:
      return campaignType.reason;
  }
}

function formatAge(ms: number): string {
  const hours = Math.floor(ms / (60 * 60 * 1000));
  if (hours < 1) return 'just now';
  if (hours < 24) return `${hours}h ago`;
  const days = Math.floor(hours / 24);
  return `${days}d ago`;
}
