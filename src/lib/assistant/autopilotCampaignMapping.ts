/**
 * Maps a trigger type to the recommended campaign type.
 * Uses direct deterministic mapping for known triggers,
 * falls back to recommendCampaignType for ambiguous cases.
 */
export function mapTriggerToCampaignType(
  triggerType: AutopilotTriggerType,
  propertyData: Record<string, unknown>,
  adapter: IndustryAdapter = getAdapter('real_estate'),
): CampaignTypeRecommendation {
  return adapter.mapTriggerToCampaignType(triggerType, propertyData);
}

/**
 * Produces a full structured recommendation for a trigger event.
 * This is the primary entry point for the mapping layer.
 */
export function buildTriggerRecommendation(
  triggerType: AutopilotTriggerType,
  propertyData: Record<string, unknown>,
  adapter: IndustryAdapter = getAdapter('real_estate'),
): TriggerCampaignRecommendation {
  const campaignType = adapter.mapTriggerToCampaignType(triggerType, propertyData);
  const triggerConf = adapter.triggerConfig[triggerType];
  const urgency = triggerConf?.urgency ?? 'normal';
  const angleHints = triggerConf?.angleHints ?? ['promotional'];
  const statusAction = resolveStatusAction(triggerType, propertyData);

  // Auto-generate only when confidence is high and trigger is deterministic
  const autoGenerateDraft =
    (triggerConf?.autoGenerate ?? false) &&
    campaignType.confidence === 'high' &&
    statusAction === 'generate';

  const rationale = buildRationale(triggerType, campaignType, propertyData);

  return {
    campaignType,
    urgency,
    angleHints,
    autoGenerateDraft,
    rationale,
    statusAction,
  };
}

/**
 * Checks whether a new recommendation should be created given recent history.
 * Prevents spamming duplicate recommendations for the same listing/event.
 */
export function checkDedupe(
  triggerType: AutopilotTriggerType,
  listingDataItemId: string,
  context: DedupeContext,
): DedupeResult {
  const now = Date.now();

  // Filter to active (non-dismissed, non-expired) recommendations
  const active = context.recentForListing.filter(
    (r) => r.status === 'pending' || r.status === 'generating' || r.status === 'ready',
  );

  // Rule 1: If the exact same trigger type exists within the cooldown window, suppress
  const sameTrigger = active.find((r) => {
    if (r.triggerType !== triggerType) return false;
    const age = now - new Date(r.createdAt).getTime();
    return age < SAME_TRIGGER_COOLDOWN_MS;
  });

  if (sameTrigger) {
    return {
      shouldCreate: false,
      suppressReason: `A ${triggerType} recommendation already exists for this listing (created ${formatAge(now - new Date(sameTrigger.createdAt).getTime())})`,
      supersedesId: null,
    };
  }

  // Rule 2: If any recommendation for this listing was created in the dedupe window, supersede it
  // (e.g., price_drop supersedes an earlier general_promotion for the same listing)
  const recentAny = active.find((r) => {
    const age = now - new Date(r.createdAt).getTime();
    return age < DEDUPE_WINDOW_MS;
  });

  if (recentAny && shouldSupersede(triggerType, recentAny.triggerType)) {
    return {
      shouldCreate: true,
      suppressReason: null,
      supersedesId: recentAny.id,
    };
  }

  // Rule 3: If there's already a pending/ready rec in the dedupe window but we can't supersede, suppress
  if (recentAny && !shouldSupersede(triggerType, recentAny.triggerType)) {
    return {
      shouldCreate: false,
      suppressReason: `A ${recentAny.triggerType} recommendation already exists for this listing within 24h`,
      supersedesId: null,
    };
  }

  return { shouldCreate: true, suppressReason: null, supersedesId: null };
}

// ── Full Autopilot Campaign Context (for display) ────────────────────────

export interface AutopilotCampaignContext {
  campaignType: CampaignTypeRecommendation;
  channels: ChannelRecommendation;
  media: MediaPrioritization | null;
  schedule: ScheduleRecommendation;
  /** Structured recommendation metadata */
  recommendation: TriggerCampaignRecommendation;
  /** Preferences context string for generation prompts (injected by hook, not computed here) */
  preferencesContext?: string | null;
}

/**
 * Composes all intelligence functions into a full context for display.
 * Used by AutopilotCampaignCard to show *why* a campaign was recommended.
 */
export function buildAutopilotCampaignContext(
  input: {
    triggerType: AutopilotTriggerType;
    propertyData: Record<string, unknown>;
    connectedChannels: Channel[];
    assets?: MediaAsset[];
  },
  adapter: IndustryAdapter = getAdapter('real_estate'),
): AutopilotCampaignContext {
  const recommendation = buildTriggerRecommendation(input.triggerType, input.propertyData, adapter);
  const { campaignType } = recommendation;

  const channels = recommendChannels({
    campaignType: campaignType.recommended,
    connectedChannels: input.connectedChannels,
    hasMedia: (input.assets?.length ?? 0) > 0,
    propertyData: input.propertyData,
  }, adapter);

  const media = input.assets && input.assets.length > 0
    ? prioritizeMedia(input.assets, {
        campaignType: campaignType.recommended,
        slotCount: channels.recommended.length,
      }, adapter)
    : null;

  const schedule = buildIntelligentSchedule({
    campaignType: campaignType.recommended,
    channels: channels.recommended,
    propertyData: input.propertyData,
  }, adapter);

  return { campaignType, channels, media, schedule, recommendation };
}

