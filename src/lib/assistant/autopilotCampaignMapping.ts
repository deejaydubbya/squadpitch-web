// ── Types ────────────────────────────────────────────────────────────────

export type CampaignUrgency = 'immediate' | 'high' | 'normal' | 'low';

export type ContentAngleHint =
  | 'urgency'
  | 'promotional'
  | 'storytelling'
  | 'lifestyle'
  | 'authority'
  | 'social_proof';

export type StatusChangeAction = 'generate' | 'pause' | 'skip';

/**
 * Structured recommendation output for a single trigger event.
 * This is the primary return type of the mapping layer.
 */
export interface TriggerCampaignRecommendation {
  /** Recommended campaign type from the assistant taxonomy */
  campaignType: CampaignTypeRecommendation;
  /** Urgency — determines how quickly the user should act */
  urgency: CampaignUrgency;
  /** Content angle hints for generation (ordered by priority) */
  angleHints: ContentAngleHint[];
  /** Whether generation should auto-proceed to draft-prep without user clicking "Generate" */
  autoGenerateDraft: boolean;
  /** Human-readable summary of why this recommendation was made */
  rationale: string;
  /** For status_changed triggers: whether to generate, pause existing, or skip */
  statusAction: StatusChangeAction;
}

/**
 * Input for deduplication check.
 * Caller passes recent recommendations to avoid spamming duplicates.
 */
export interface DedupeContext {
  /** Existing recommendation IDs for this listing, with their trigger types and timestamps */
  recentForListing: Array<{
    id: string;
    triggerType: AutopilotTriggerType;
    createdAt: string;
    status: string;
  }>;
}

/**
 * Result of deduplication check.
 */
export interface DedupeResult {
  /** Whether this recommendation should proceed */
  shouldCreate: boolean;
  /** If suppressed, why */
  suppressReason: string | null;
  /** If an existing recommendation should be superseded instead of creating new */
  supersedesId: string | null;
}

// ── Deduplication window (ms) ────────────────────────────────────────────

const DEDUPE_WINDOW_MS = 24 * 60 * 60 * 1000; // 24 hours
const SAME_TRIGGER_COOLDOWN_MS = 7 * 24 * 60 * 60 * 1000; // 7 days for same trigger type

// ══════════════════════════════════════════════════════════════════════════
